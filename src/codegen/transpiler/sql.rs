    // Match patterns
    // ------------------------------------------------------------------

    /// One `WHEN`-arm condition for a single pattern. Native semantics
    /// (match_lowering.rs): integer/range/string comparisons, and enum
    /// variants compared by name; ranges are INCLUSIVE on both ends.
    fn pattern_cond(&mut self, scrut: &str, pat: &str, ctn: &str, span: Span) -> String {
        if let Some((start, end)) = pat.split_once("..")
            && start.parse::<i64>().is_ok()
            && end.parse::<i64>().is_ok()
        {
            return format!("({} >= {} AND {} <= {})", scrut, start, scrut, end);
        }
        if let Some(lit) = pat.strip_prefix('"').and_then(|s| s.strip_suffix('"')) {
            return format!("{} = {}", scrut, sql_string(lit));
        }
        if pat.parse::<i64>().is_ok() {
            return format!("{} = {}", scrut, pat);
        }
        // Enum path (`Color::Red`, `Color.Red`) or bare variant name.
        let variant = pat.rsplit([':', '.']).next().unwrap_or(pat);
        if let Some(e) = self.enums.get(ctn)
            && e.variants.iter().any(|v| v.name == variant)
        {
            return format!("{} = '{}'", scrut, variant);
        }
        if self
            .enums
            .values()
            .any(|e| e.variants.iter().any(|v| v.name == variant))
        {
            return format!("{} = '{}'", scrut, variant);
        }
        self.warn(
            span,
            format!("unknown pattern '{}' — emitted as a text comparison", pat),
        );
        format!("{} = '{}'", scrut, variant)
    }

    /// The `WHEN`-arm condition for a match arm, shared by the statement
    /// and expression forms (guard conjoined with the pattern
    /// conditions). Returns `None` when the arm uses binding params (the
    /// error is recorded here).
    fn match_arm_cond(
        &mut self,
        scrut: &str,
        arm: &MatchArm,
        ctn: &str,
        span: Span,
    ) -> Option<String> {
        if !arm.params.is_empty() {
            self.error(
                span,
                format!(
                    "binding pattern '{}' cannot be transpiled — SQL has no payload extraction; match the scrutinee directly",
                    arm.pattern
                ),
            );
            return None;
        }
        let pats = if arm.patterns.is_empty() {
            vec![arm.pattern.clone()]
        } else {
            arm.patterns.clone()
        };
        let conds: Vec<String> = pats
            .iter()
            .map(|p| {
                if *p == "_" {
                    // Guarded default (`_ if cond`): matches everything,
                    // the guard does the filtering.
                    "TRUE".to_string()
                } else {
                    self.pattern_cond(scrut, p, ctn, span)
                }
            })
            .collect();
        let mut cond = conds.join(" OR ");
        if let Some(g) = &arm.guard {
            let guard_sql = self.expr_sql(g);
            cond = format!("({}) AND ({})", cond, guard_sql);
        }
        Some(cond)
    }

